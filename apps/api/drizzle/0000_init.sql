CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TYPE rol_asistente AS ENUM ('estudiante', 'docente');
CREATE TYPE rol_sistema AS ENUM ('admin', 'operador');
CREATE TYPE estado_lote AS ENUM ('en_proceso', 'completado', 'fallido');

-- Funcion auxiliar para mantener updated_at sin depender de la capa de aplicacion.
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- -----------------------------------------------------------------------------
-- usuarios_sistema: administradores y operadores
-- -----------------------------------------------------------------------------
CREATE TABLE usuarios_sistema (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nombre text NOT NULL CHECK (length(btrim(nombre)) >= 3),
  email text NOT NULL CHECK (length(btrim(email)) >= 5),
  password_hash text NOT NULL,
  rol rol_sistema NOT NULL,
  activo boolean NOT NULL DEFAULT true,
  ultimo_acceso_at timestamptz,
  creado_por uuid REFERENCES usuarios_sistema(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX usuarios_sistema_email_idx ON usuarios_sistema (lower(email));
CREATE INDEX usuarios_sistema_rol_idx ON usuarios_sistema (rol);

CREATE TRIGGER usuarios_sistema_updated_at
  BEFORE UPDATE ON usuarios_sistema
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- -----------------------------------------------------------------------------
-- refresh_tokens: rotacion por dispositivo, el hash nunca se guarda en claro
-- -----------------------------------------------------------------------------
CREATE TABLE refresh_tokens (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  usuario_id uuid NOT NULL REFERENCES usuarios_sistema(id) ON DELETE CASCADE,
  token_hash text NOT NULL UNIQUE,
  expira_at timestamptz NOT NULL,
  revocado boolean NOT NULL DEFAULT false,
  user_agent text,
  ip inet,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX refresh_tokens_usuario_idx ON refresh_tokens (usuario_id, revocado);

-- -----------------------------------------------------------------------------
-- seminario_config: fila unica (id = 1) con los parametros del evento
-- -----------------------------------------------------------------------------
CREATE TABLE seminario_config (
  id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  nombre text NOT NULL CHECK (length(btrim(nombre)) >= 3),
  fecha date NOT NULL,
  hora_fin_seminario timestamptz NOT NULL,
  tolerancia_minutos integer NOT NULL DEFAULT 0
    CHECK (tolerancia_minutos BETWEEN 0 AND 240),
  exigir_ambas_jornadas boolean NOT NULL DEFAULT true,
  intensidad_horaria integer NOT NULL DEFAULT 8
    CHECK (intensidad_horaria BETWEEN 1 AND 24),
  permitir_registro_fuera_de_ventana boolean NOT NULL DEFAULT false,
  texto_encabezado text,
  texto_cierre text,
  firma_nombre text,
  firma_cargo text,
  id_regex text NOT NULL DEFAULT '^[A-Z0-9]{4,20}$',
  url_publica text,
  creado_por uuid REFERENCES usuarios_sistema(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TRIGGER seminario_config_updated_at
  BEFORE UPDATE ON seminario_config
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- -----------------------------------------------------------------------------
-- jornadas: manana y tarde con su ventana de check-in
-- -----------------------------------------------------------------------------
CREATE TABLE jornadas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL CHECK (length(btrim(nombre)) >= 2),
  inicio timestamptz NOT NULL,
  fin timestamptz NOT NULL,
  ventana_checkin_inicio timestamptz NOT NULL,
  ventana_checkin_fin timestamptz NOT NULL,
  orden integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT jornadas_fin_posterior CHECK (fin > inicio),
  CONSTRAINT jornadas_ventana_valida CHECK (ventana_checkin_fin > ventana_checkin_inicio)
);

CREATE TRIGGER jornadas_updated_at
  BEFORE UPDATE ON jornadas
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- -----------------------------------------------------------------------------
-- asistentes: el ID institucional es la clave de negocio, unica e inmutable
-- -----------------------------------------------------------------------------
CREATE TABLE asistentes (
  id text PRIMARY KEY CHECK (length(btrim(id)) >= 2),
  nombres text NOT NULL CHECK (length(btrim(nombres)) >= 1),
  apellidos text NOT NULL CHECK (length(btrim(apellidos)) >= 1),
  semestre integer,
  rol rol_asistente NOT NULL,
  activo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT asistentes_semestre_rol CHECK ((rol = 'estudiante') = (semestre IS NOT NULL)),
  CONSTRAINT asistentes_semestre_rango CHECK (semestre IS NULL OR semestre BETWEEN 1 AND 30)
);

CREATE INDEX asistentes_apellidos_idx ON asistentes (lower(apellidos));
CREATE INDEX asistentes_nombres_idx ON asistentes (lower(nombres));
CREATE INDEX asistentes_rol_idx ON asistentes (rol);
CREATE INDEX asistentes_semestre_idx ON asistentes (semestre);
CREATE INDEX asistentes_busqueda_trgm_idx
  ON asistentes USING gin ((nombres || ' ' || apellidos) gin_trgm_ops);

CREATE TRIGGER asistentes_updated_at
  BEFORE UPDATE ON asistentes
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- -----------------------------------------------------------------------------
-- asistencias: UNIQUE (asistente_id, jornada_id) garantiza un solo ingreso
-- -----------------------------------------------------------------------------
CREATE TABLE asistencias (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asistente_id text NOT NULL REFERENCES asistentes(id) ON DELETE RESTRICT,
  jornada_id integer NOT NULL REFERENCES jornadas(id) ON DELETE RESTRICT,
  hora_ingreso timestamptz NOT NULL DEFAULT now(),
  hora_salida timestamptz,
  registrado_por uuid REFERENCES usuarios_sistema(id) ON DELETE SET NULL,
  registrado_salida_por uuid REFERENCES usuarios_sistema(id) ON DELETE SET NULL,
  dispositivo text,
  idempotency_key text,
  excepcion_manual boolean NOT NULL DEFAULT false,
  motivo_excepcion text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT asistencias_unico_asistente_jornada UNIQUE (asistente_id, jornada_id),
  CONSTRAINT asistencias_salida_posterior CHECK (hora_salida IS NULL OR hora_salida >= hora_ingreso)
);

CREATE INDEX asistencias_jornada_hora_idx ON asistencias (jornada_id, hora_ingreso);
CREATE INDEX asistencias_hora_ingreso_idx ON asistencias (hora_ingreso);
CREATE INDEX asistencias_idempotency_idx ON asistencias (idempotency_key);
CREATE INDEX asistencias_registrado_por_idx ON asistencias (registrado_por);

CREATE TRIGGER asistencias_updated_at
  BEFORE UPDATE ON asistencias
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- -----------------------------------------------------------------------------
-- tipos_refrigerio y entregas_refrigerio
-- -----------------------------------------------------------------------------
CREATE TABLE tipos_refrigerio (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL CHECK (length(btrim(nombre)) >= 2),
  jornada_id integer NOT NULL REFERENCES jornadas(id) ON DELETE RESTRICT,
  activo boolean NOT NULL DEFAULT true,
  orden integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX tipos_refrigerio_nombre_jornada_idx
  ON tipos_refrigerio (lower(nombre), jornada_id);

CREATE TRIGGER tipos_refrigerio_updated_at
  BEFORE UPDATE ON tipos_refrigerio
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE entregas_refrigerio (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asistente_id text NOT NULL REFERENCES asistentes(id) ON DELETE RESTRICT,
  tipo_refrigerio_id integer NOT NULL REFERENCES tipos_refrigerio(id) ON DELETE RESTRICT,
  entregado_at timestamptz NOT NULL DEFAULT now(),
  entregado_por uuid REFERENCES usuarios_sistema(id) ON DELETE SET NULL,
  dispositivo text,
  idempotency_key text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT entregas_unico_asistente_tipo UNIQUE (asistente_id, tipo_refrigerio_id)
);

CREATE INDEX entregas_tipo_idx ON entregas_refrigerio (tipo_refrigerio_id, entregado_at);
CREATE INDEX entregas_hora_idx ON entregas_refrigerio (entregado_at);
CREATE INDEX entregas_idempotency_idx ON entregas_refrigerio (idempotency_key);

-- -----------------------------------------------------------------------------
-- certificados_lotes y certificados
-- -----------------------------------------------------------------------------
CREATE TABLE certificados_lotes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  solicitado_por uuid REFERENCES usuarios_sistema(id) ON DELETE SET NULL,
  estado estado_lote NOT NULL DEFAULT 'en_proceso',
  total integer NOT NULL DEFAULT 0 CHECK (total >= 0),
  procesados integer NOT NULL DEFAULT 0 CHECK (procesados >= 0),
  exitosos integer NOT NULL DEFAULT 0 CHECK (exitosos >= 0),
  fallidos integer NOT NULL DEFAULT 0 CHECK (fallidos >= 0),
  errores jsonb NOT NULL DEFAULT '[]'::jsonb,
  motivo text,
  iniciado_at timestamptz NOT NULL DEFAULT now(),
  finalizado_at timestamptz
);

CREATE INDEX certificados_lotes_estado_idx ON certificados_lotes (estado, iniciado_at DESC);

CREATE TABLE certificados (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  asistente_id text NOT NULL UNIQUE REFERENCES asistentes(id) ON DELETE RESTRICT,
  codigo_verificacion text NOT NULL UNIQUE,
  emitido_at timestamptz NOT NULL DEFAULT now(),
  emitido_por uuid REFERENCES usuarios_sistema(id) ON DELETE SET NULL,
  hash_pdf text NOT NULL,
  revocado boolean NOT NULL DEFAULT false,
  motivo_revocacion text,
  excepcion_manual boolean NOT NULL DEFAULT false,
  motivo_excepcion text,
  lote_id uuid REFERENCES certificados_lotes(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX certificados_lote_idx ON certificados (lote_id);

CREATE TRIGGER certificados_updated_at
  BEFORE UPDATE ON certificados
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- -----------------------------------------------------------------------------
-- auditoria: registro inmutable de acciones sensibles
-- -----------------------------------------------------------------------------
CREATE TABLE auditoria (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id uuid REFERENCES usuarios_sistema(id) ON DELETE SET NULL,
  usuario_nombre text,
  accion text NOT NULL,
  entidad text NOT NULL,
  entidad_id text,
  datos_antes jsonb,
  datos_despues jsonb,
  ip inet,
  user_agent text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX auditoria_created_at_idx ON auditoria (created_at DESC);
CREATE INDEX auditoria_entidad_idx ON auditoria (entidad, entidad_id);
CREATE INDEX auditoria_usuario_idx ON auditoria (usuario_id);

-- -----------------------------------------------------------------------------
-- idempotencia: respaldo en base de datos de la cabecera Idempotency-Key
-- -----------------------------------------------------------------------------
CREATE TABLE idempotencia (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id uuid REFERENCES usuarios_sistema(id) ON DELETE CASCADE,
  endpoint text NOT NULL,
  clave text NOT NULL,
  codigo_http integer NOT NULL,
  cuerpo jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT idempotencia_unica UNIQUE (usuario_id, endpoint, clave)
);

CREATE INDEX idempotencia_created_at_idx ON idempotencia (created_at);

